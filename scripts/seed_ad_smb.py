GROUPS = ["IT", "HR", "FIN", "CS", "RMC"]
BASE_NAMES = ["James", "Mary", "Robert", "Patricia", "John", "Jennifer", "Michael", "Linda", "David", "Elizabeth", "William", "Barbara", "Richard", "Susan", "Joseph", "Jessica", "Thomas", "Sarah", "Charles", "Karen", "Christopher", "Nancy", "Daniel", "Lisa", "Matthew", "Betty", "Anthony", "Margaret", "Mark", "Sandra", "Donald", "Ashley", "Steven", "Kimberly", "Paul", "Emily", "Andrew", "Donna", "Joshua", "Michelle", "Kenneth", "Dorothy", "Kevin", "Carol", "Brian", "Amanda", "George", "Melissa", "Edward", "Deborah", "Azman"]

def generate_users():
    """Pre-generate users in Python to ensure consistency with generated SQL."""
    users = []
    # Generate 10 users per group
    for group in GROUPS:
        for i in range(1, 11):
            base_name = random.choice(BASE_NAMES)
            if i == 1 and group == "IT":
                base_name = "Azman"
            
            username = f"{group}_{base_name}"
            # Unique suffix to avoid duplicates in seeding
            username = f"{username}_{random.randint(100, 999)}"
            users.append({"username": username, "group": group})
    return users

def generate_user_sql(users):
    """Generate SQL file for inserting users into user_account and user_role tables."""
    ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"create_{ts}_users.sql"
    password = "Password123!"
    
    with open(filename, "w") as f:
        f.write("-- SQL to seed users generated by seed_ad_smb.py\n")
        f.write(f"-- Generated at: {datetime.datetime.now().isoformat()}\n\n")
        
        for user in users:
            uname = user['username']
            # Using ON CONFLICT (username) DO NOTHING to avoid errors on re-run
            f.write(f"INSERT INTO user_account (username, password) VALUES ('{uname}', '{password}') ON CONFLICT (username) DO NOTHING;\n")
            # Link to the 'USER' role
            f.write(f"INSERT INTO user_role (user_id, role_id) SELECT id, (SELECT id FROM role WHERE name = 'USER') FROM user_account WHERE username = '{uname}' AND NOT EXISTS (SELECT 1 FROM user_role ur JOIN role r ON ur.role_id = r.id WHERE ur.user_id = user_account.id AND r.name = 'USER');\n\n")
            
    return filename


def main():
    parser = argparse.ArgumentParser(description="Seed Windows Server with AD Users and custom SMB structure.")
    parser.add_argument("--host", required=True)
    parser.add_argument("--domain", default="DEV")
    parser.add_argument("--path", required=True)
    parser.add_argument("--user", required=True)
    parser.add_argument("--password", required=True)
    parser.add_argument("--transport", default="ntlm", choices=["ntlm", "kerberos", "basic", "credssp"])
    parser.add_argument("--cert-validation", default="ignore", choices=["ignore", "validate"])
    
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--create", type=int, help="Seed both AD and Files/Folders.")
    group.add_argument("--delete", action="store_true")

    parser.add_argument("--exception", action="store_true")
    args = parser.parse_args()

    try:
        session = winrm.Session(
            args.host,
            auth=(args.user, args.password),
            transport=args.transport,
            server_cert_validation=('ignore' if args.cert_validation == 'ignore' else 'validate')
        )
        
        pregenerated_users = []
        if args.create is not None:
            print("Generating User seeding SQL (Application side)...")
            pregenerated_users = generate_users()
            sql_file = generate_user_sql(pregenerated_users)
            print(f"Created: {sql_file}")
        
        ps_script = generate_powershell_script(
            args.domain, pregenerated_users, root_path=args.path,
            total_count=args.create if args.create is not None else 10000, 
            with_exception=args.exception, delete_only=args.delete
        )
        
        print("Uploading and executing remote PowerShell payload...")
        import base64
        b64_script = base64.b64encode(ps_script.encode('utf-8')).decode('utf-8')
        session.run_cmd(r'powershell -Command "if (Test-Path C:\Windows\Temp\seed.b64) { Remove-Item C:\Windows\Temp\seed.b64 -Force }"')
        for i in range(0, len(b64_script), 2000):
            chunk = b64_script[i:i+2000]
            session.run_cmd(f'cmd.exe /c echo {chunk}>> C:\\Windows\\Temp\\seed.b64')
            
        decoder_ps = r"""
        $b64 = Get-Content C:\Windows\Temp\seed.b64 -Raw
        $b64 = $b64 -replace "`r", "" -replace "`n", "" -replace " ", ""
        $bytes = [System.Convert]::FromBase64String($b64)
        $script = [System.Text.Encoding]::UTF8.GetString($bytes)
        $script | Out-File C:\Windows\Temp\seed.ps1 -Encoding UTF8 -Force
        & C:\Windows\Temp\seed.ps1
        """
        result = session.run_ps(decoder_ps)
        if result.status_code == 0:
            print("[SUCCESS] PowerShell seeding complete.")
            if result.std_out: print(result.std_out.decode('utf-8'))
        else:
            print(f"[ERROR] PsCode {result.status_code}")
            if result.std_out: print(result.std_out.decode('utf-8'))
            if result.std_err: print(result.std_err.decode('utf-8'))

    except Exception as e:
        print(f"[CRITICAL ERROR] {e}")

if __name__ == "__main__":
    main()
